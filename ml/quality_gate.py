import json
import yaml
from pathlib import Path
from typing import Tuple, Dict, Any

LOWER_IS_BETTER = {"loss", "rmse", "mae"}


def check_quality_gate(metrics_path: str, mlops_yaml_path: str) -> Tuple[bool, Dict[str, Any]]:
    """
    Evaluates training metrics against declared thresholds in mlops.yaml.
    Supports both classification and regression task types with AND logic.

    Args:
        metrics_path: Path to metrics.json generated by training
        mlops_yaml_path: Path to mlops.yaml manifest

    Returns:
        (passed: bool, details: dict)
    """
    metrics_file = Path(metrics_path)
    if not metrics_file.exists():
        return False, {
            "overall": "failed",
            "error": f"Metrics file not found: {metrics_path}",
            "checks": {}
        }

    yaml_file = Path(mlops_yaml_path)
    if not yaml_file.exists():
        return False, {
            "overall": "failed",
            "error": f"mlops.yaml file not found: {mlops_yaml_path}",
            "checks": {}
        }

    try:
        with open(metrics_file, "r", encoding="utf-8") as f:
            metrics_data = json.load(f)
    except Exception as e:
        return False, {
            "overall": "failed",
            "error": f"Error parsing metrics.json: {str(e)}",
            "checks": {}
        }

    try:
        with open(yaml_file, "r", encoding="utf-8") as f:
            mlops_config = yaml.safe_load(f)
    except Exception as e:
        return False, {
            "overall": "failed",
            "error": f"Error parsing mlops.yaml: {str(e)}",
            "checks": {}
        }

    task_type = mlops_config.get("task_type", "classification")
    metrics_threshold = mlops_config.get("metrics_threshold", {})

    if not metrics_threshold:
        return True, {
            "overall": "passed",
            "task_type": task_type,
            "message": "No thresholds declared; gate automatically passed.",
            "checks": {}
        }

    checks: Dict[str, Any] = {}
    all_passed = True

    for metric_name, threshold_val in metrics_threshold.items():
        if metric_name not in metrics_data:
            checks[metric_name] = {
                "value": None,
                "threshold": threshold_val,
                "passed": False,
                "error": f"Metric '{metric_name}' missing from metrics.json"
            }
            all_passed = False
            continue

        actual_val = metrics_data[metric_name]
        try:
            actual_float = float(actual_val)
            threshold_float = float(threshold_val)
        except (ValueError, TypeError):
            checks[metric_name] = {
                "value": actual_val,
                "threshold": threshold_val,
                "passed": False,
                "error": "Non-numeric metric or threshold"
            }
            all_passed = False
            continue

        # Comparison logic: lower is better for loss/rmse/mae, higher is better for accuracy/f1/precision/recall/r_squared
        if metric_name.lower() in LOWER_IS_BETTER:
            is_metric_pass = actual_float <= threshold_float
        else:
            is_metric_pass = actual_float >= threshold_float

        checks[metric_name] = {
            "value": actual_float,
            "threshold": threshold_float,
            "passed": is_metric_pass,
            "comparison": "<=" if metric_name.lower() in LOWER_IS_BETTER else ">="
        }

        if not is_metric_pass:
            all_passed = False

    details = {
        "overall": "passed" if all_passed else "failed",
        "task_type": task_type,
        "checks": checks
    }

    return all_passed, details
